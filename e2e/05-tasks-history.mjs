import { BASE, checker, launch, shotPath } from './helpers.mjs'
const { check, finish } = checker()
const browser = await launch()
const page = await (await browser.newContext({ viewport: { width: 900, height: 700 } })).newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message)); page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto(BASE)
const src = 'Todo:\n- [ ] 1\n- [ ] 2\n    - [ ] 3\n      - [x] 4\n1. [ ] numbered\n\n```\n- [ ] not a task\n```'
const c = page.getByLabel('Write to Inbox')
await c.fill(src); await c.press('Enter')
const card = page.locator('.msg').first()
await card.locator('.md').waitFor()
const boxes = card.locator('.md input[type=checkbox]')
check('five real checkboxes, none from the code block', (await boxes.count()) === 5)
check('checkboxes are enabled', (await boxes.evaluateAll((els) => els.every((e) => !e.disabled))))
await boxes.nth(2).click()
await card.locator('time', { hasText: 'edited' }).waitFor()
await card.hover(); await card.getByRole('button', { name: 'Edit' }).click()
const after1 = await card.getByLabel('Edit message').inputValue()
check('clicking item 3 flips only its marker', after1 === src.replace('    - [ ] 3', '    - [x] 3'), JSON.stringify(after1))
await card.getByLabel('Edit message').press('Escape')
check('nested item 4 still checked, others unchecked', JSON.stringify(await boxes.evaluateAll((els) => els.map((e) => e.checked))) === JSON.stringify([false, false, true, true, false]))
await boxes.nth(3).click()
await page.waitForFunction(() => document.querySelector('.msg .md input:nth-of-type(1)') && [...document.querySelectorAll('.msg .md input')][3].checked === false)
await boxes.nth(4).click()
await page.waitForFunction(() => [...document.querySelectorAll('.msg .md input')][4].checked === true)
await card.hover(); await card.getByRole('button', { name: 'Edit' }).click()
const after3 = await card.getByLabel('Edit message').inputValue()
check('untick nested [x] and tick numbered item', after3 === src.replace('    - [ ] 3', '    - [x] 3').replace('      - [x] 4', '      - [ ] 4').replace('1. [ ] numbered', '1. [x] numbered'), JSON.stringify(after3))
await card.getByLabel('Edit message').press('Escape')
await card.hover()
check('each click made a version', await card.getByRole('button', { name: 'History · 3' }).isVisible())
await card.getByRole('button', { name: 'History · 3' }).click()
const nav = card.locator('.vnav'); await nav.waitFor()
const states = () => card.locator('.md input[type=checkbox]').evaluateAll((els) => els.map((e) => e.checked))
check('history opens at the current version', (await nav.locator('.vnav-pos').innerText()).replace(/\s+/g, ' ').trim() === '4 of 4 current')
check('newer is disabled at current', await nav.getByRole('button', { name: 'Newer version' }).isDisabled())
await nav.getByRole('button', { name: 'Older version' }).click()
await page.waitForFunction(() => document.querySelector('.vnav-pos')?.textContent?.startsWith('3 of 4'))
check('older shows the previous state in place', JSON.stringify(await states()) === '[false,false,true,false,false]', JSON.stringify(await states()))
check('earlier version is read-only', (await card.locator('.md input[type=checkbox]').evaluateAll((els) => els.every((e) => e.disabled))) && (await card.locator('.vnav-note').innerText()) === 'Viewing an earlier version')
await nav.getByRole('button', { name: 'Older version' }).click()
await nav.getByRole('button', { name: 'Older version' }).click()
await page.waitForFunction(() => document.querySelector('.vnav-pos')?.textContent?.startsWith('1 of 4'))
check('reaches the original and stops', JSON.stringify(await states()) === '[false,false,false,true,false]' && (await nav.getByRole('button', { name: 'Older version' }).isDisabled()))
await nav.getByRole('button', { name: 'Newer version' }).click()
await page.waitForFunction(() => document.querySelector('.vnav-pos')?.textContent?.startsWith('2 of 4'))
check('newer steps forward', JSON.stringify(await states()) === '[false,false,true,true,false]')
// Calendar modal
await nav.locator('.vnav-time').click()
const dlg = page.locator('dialog.cal-dialog')
await dlg.waitFor()
check('calendar opens as a modal', await dlg.evaluate((d) => d.open))
check('only today has versions and is selected', (await dlg.locator('.cal-day.has').count()) === 1 && (await dlg.locator('.cal-day.selected.has').count()) === 1 && (await dlg.locator('.cal-day:not(.has):not(:disabled)').count()) === 0)
check('day panel lists every version of the day', (await dlg.locator('.cal-list li .cal-version').count()) === 4)
const monthBefore = await dlg.locator('.cal-month-name').innerText()
await dlg.getByRole('button', { name: 'Previous month' }).click()
check('month navigation works and empty months have no active days', (await dlg.locator('.cal-month-name').innerText()) !== monthBefore && (await dlg.locator('.cal-day.has').count()) === 0)
await dlg.getByRole('button', { name: 'Next month' }).click()
await dlg.locator('.cal-list li .cal-version').last().click()
await dlg.waitFor({ state: 'detached' })
await page.waitForFunction(() => document.querySelector('.vnav-pos')?.textContent?.startsWith('1 of 4'))
check('picking a version from the calendar jumps to it and closes', JSON.stringify(await states()) === '[false,false,false,true,false]')
await nav.getByRole('button', { name: 'Newer version' }).click(); await nav.getByRole('button', { name: 'Newer version' }).click(); await nav.getByRole('button', { name: 'Newer version' }).click()
await page.waitForFunction(() => document.querySelector('.vnav-pos')?.textContent?.startsWith('4 of 4'))
check('back at current, checkboxes live again', await card.locator('.md input[type=checkbox]').evaluateAll((els) => els.every((e) => !e.disabled)))
await nav.locator('.vnav-time').click(); await dlg.waitFor(); await page.keyboard.press('Escape'); await dlg.waitFor({ state: 'detached' })
check('Escape closes the calendar', true)
await page.screenshot({ path: shotPath('v3-task-toggle.png') })
check('no console errors', errors.length === 0, errors.join(' | '))
await finish(browser)
